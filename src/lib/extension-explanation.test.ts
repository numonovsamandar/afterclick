import { afterEach, describe, expect, it, vi } from 'vitest';
import { analyzeDomain, analyzeMessage } from './inspector';
import { analyzePageContent } from './page-content-inspector';
import { prepareCloudScan, redactScanText } from './scan-privacy';
import { explainScan, scanEvidence, validateExplanations } from './extension-explanation';
import { handleExtensionApi } from './extension-api';

afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs(); });
const sample = { text: 'Urgent: confirm your password immediately.', url: '', links: [] };

describe('scan precision', () => {
  it('does not treat security reminders and receipts as high severity requests', () => {
    for (const text of ['Never share your verification code.', 'Do not send your password.', 'Password settings', 'Your refund of $12.00 was processed.']) {
      expect(analyzeMessage(text).findings.filter((f) => f.severity === 'high')).toHaveLength(0);
    }
    expect(analyzeMessage('Never share your code. Send me the verification code now.').findings.some((f) => f.kind === 'code' && f.severity === 'high')).toBe(true);
  });
  it('distinguishes tenants on shared hosting and catches repeated-link disguises', () => {
    expect(analyzeDomain('https://paypal-login.github.io').registrableDomain).toBe('paypal-login.github.io');
    expect(analyzePageContent('', [
      { text: 'Read more', href: 'https://attacker.example/x' },
      { text: 'paypal.com', href: 'https://attacker.example/x' },
    ]).linkMismatches).toHaveLength(1);
  });
});

describe('cloud scan privacy and evidence', () => {
  it('removes tokens, emails, numeric secrets and URL paths without damaging domains', () => {
    const clean = prepareCloudScan({ text: 'Contact sam@example.com password: secret123 code 123456 https://paypal.com.bad.top/login?token=secret#frag', url: 'https://user:pass@example.com/private?token=secret', links: [] });
    const serialized = JSON.stringify(clean);
    for (const secret of ['sam@example.com', 'secret123', '123456', 'login?', 'token=secret', 'user:pass', '/private']) expect(serialized).not.toContain(secret);
    expect(clean.text).toContain('https://paypal.com.bad.top/');
    expect(clean.text).not.toContain('https://https://');
    expect(redactScanText(clean.text)).toBe(clean.text);
  });
  it('rejects model evidence IDs not generated by the inspector', () => {
    expect(() => validateExplanations({ explanations: [{ findingId: 'invented', explanation: 'Claim' }] }, scanEvidence(sample))).toThrow();
  });
  it('sends evidence only and handles quota errors without exposing provider responses', async () => {
    vi.stubEnv('OPENAI_API_KEY', 'test-key');
    const fetcher = vi.fn().mockResolvedValue(new Response('{}', { status: 429 }));
    vi.stubGlobal('fetch', fetcher);
    await expect(explainScan({ ...sample, text: sample.text + ' Private unrelated sentence.' })).rejects.toThrow('quota');
    const body = JSON.parse(fetcher.mock.calls[0]![1].body);
    expect(body.store).toBe(false);
    expect(body.input).not.toContain('Private unrelated sentence');
    expect(body.tools).toBeUndefined();
  });
  it('does not call AI when no indicators are found', async () => {
    const fetcher = vi.fn(); vi.stubGlobal('fetch', fetcher);
    expect((await explainScan({ text: 'See you at lunch', url: '', links: [] })).findings).toEqual([]);
    expect(fetcher).not.toHaveBeenCalled();
  });
  it('attaches validated AI explanations to authoritative evidence', async () => {
    vi.stubEnv('OPENAI_API_KEY', 'test-key');
    const finding = scanEvidence(sample)[0]!;
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(Response.json({ status: 'completed', output: [{ content: [{ type: 'output_text', text: JSON.stringify({ explanations: [{ findingId: finding.id, explanation: 'This wording asks for an account action; the sender has not been verified.' }] }) }] }] })));
    const result = await explainScan(sample);
    expect(result.findings[0]).toMatchObject({ id: finding.id, evidence: finding.evidence, severity: finding.severity });
    expect(result.findings[0]?.aiExplanation).toContain('not been verified');
  });
  it('enforces origin, content type, validation and body limits at the API', async () => {
    const url = 'https://afterclick-nine.vercel.app/api/extension/explain';
    expect((await handleExtensionApi(new Request(url, { method: 'POST' }))).status).toBe(403);
    const origin = 'chrome-extension://' + 'a'.repeat(32);
    expect((await handleExtensionApi(new Request(url, { method: 'OPTIONS', headers: { origin } }))).status).toBe(204);
    expect((await handleExtensionApi(new Request(url, { method: 'POST', headers: { origin, 'content-type': 'application/json' }, body: JSON.stringify({ text: 'x'.repeat(160_000) }) }))).status).toBe(413);
    expect((await handleExtensionApi(new Request(url, { method: 'POST', headers: { origin, 'content-type': 'application/json' }, body: '{}' }))).status).toBe(400);
  });
});
