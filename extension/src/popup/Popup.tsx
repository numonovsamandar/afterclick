import { useState, useEffect, useCallback } from 'react';
import {
  Shield, ShieldAlert, ShieldCheck, ShieldQuestion,
  ExternalLink, AlertTriangle, Copy, RotateCcw,
  Globe, Lock, Unlock, Eye, ChevronDown, ChevronUp,
  KeyRound, MessageSquareWarning, DollarSign, MousePointerClick, MonitorSmartphone,
  Download, CheckCircle2,
} from 'lucide-react';
import { analyzeDomain, analyzeMessage, type Analysis, type DomainAnalysis } from '@/lib/inspector';
import { analyzePageContent, type PageContentAnalysis } from '@/lib/page-content-inspector';
import { getIncidentUrl, isRestrictedUrl, WEBSITE_URL, INCIDENT_ROUTES } from '@/lib/constants';

type View = 'home' | 'url-results' | 'page-results' | 'emergency';

interface TabInfo {
  url: string;
  title: string;
  tabId?: number;
}

export function Popup() {
  const [view, setView] = useState<View>('home');
  const [tabInfo, setTabInfo] = useState<TabInfo | null>(null);
  const [urlAnalysis, setUrlAnalysis] = useState<DomainAnalysis | null>(null);
  const [pageAnalysis, setPageAnalysis] = useState<PageContentAnalysis | null>(null);
  const [pageError, setPageError] = useState<string | null>(null);
  const [inspectingPage, setInspectingPage] = useState(false);
  const [copied, setCopied] = useState(false);
  const [restricted, setRestricted] = useState(false);

  useEffect(() => {
    chrome.runtime.sendMessage({ type: 'GET_TAB_INFO' }, (info: TabInfo) => {
      if (info?.url) {
        setTabInfo(info);
        if (isRestrictedUrl(info.url)) {
          setRestricted(true);
        }
      }
    });
  }, []);

  const inspectUrl = useCallback(() => {
    if (!tabInfo?.url || restricted) return;
    const domain = analyzeDomain(tabInfo.url);
    setUrlAnalysis(domain);
    setView('url-results');
  }, [tabInfo, restricted]);

  const inspectPageContent = useCallback(() => {
    if (!tabInfo?.tabId || restricted) return;
    setInspectingPage(true);
    setPageError(null);
    chrome.runtime.sendMessage(
      { type: 'INJECT_CONTENT_SCRIPT', tabId: tabInfo.tabId },
      (response: { ok: boolean; data?: { text: string; links: { text: string; href: string }[] }; error?: string }) => {
        setInspectingPage(false);
        if (!response?.ok) {
          setPageError(response?.error ?? 'Could not inspect this page. It may be a restricted or protected page.');
          return;
        }
        if (response.data) {
          const result = analyzePageContent(response.data.text, response.data.links);
          setPageAnalysis(result);
          setView('page-results');
        }
      }
    );
  }, [tabInfo, restricted]);

  const copyFindings = useCallback(() => {
    const lines: string[] = ['AfterClick Companion \u2014 Inspection Summary', ''];
    if (tabInfo) {
      lines.push(`Page: ${tabInfo.url}`, '');
    }
    if (urlAnalysis) {
      lines.push(`Hostname: ${urlAnalysis.hostname}`);
      lines.push(`Registered domain: ${urlAnalysis.registrableDomain ?? 'unknown'}`);
      lines.push(`HTTPS: ${urlAnalysis.protocol === 'https' ? 'Yes' : urlAnalysis.protocol === 'http' ? 'No' : 'N/A'}`);
      if (urlAnalysis.issues.length) {
        lines.push('', 'Issues found:');
        urlAnalysis.issues.forEach(i => lines.push(`  \u2022 [${i.severity}] ${i.message}`));
      }
      lines.push('');
    }
    if (pageAnalysis) {
      const { textAnalysis, linkMismatches } = pageAnalysis;
      if (textAnalysis.findings.length) {
        lines.push('Text warning signs:');
        textAnalysis.findings.forEach(f => lines.push(`  \u2022 [${f.severity}] ${f.title}: ${f.explanation}`));
        lines.push('');
      }
      if (linkMismatches.length) {
        lines.push('Link mismatches:');
        linkMismatches.forEach(m => lines.push(`  \u2022 Shows "${m.displayedDomain}" but goes to "${m.actualDomain}"`));
        lines.push('');
      }
    }
    lines.push('---', 'Generated by AfterClick Companion. Findings are informational \u2014 not a security guarantee.');
    navigator.clipboard.writeText(lines.join('\n'));
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }, [tabInfo, urlAnalysis, pageAnalysis]);

  const openWebsite = (url: string) => {
    chrome.runtime.sendMessage({ type: 'OPEN_WEBSITE', url });
  };

  const resetInspection = () => {
    setView('home');
    setUrlAnalysis(null);
    setPageAnalysis(null);
    setPageError(null);
  };

  return (
    <div className="w-[380px] min-h-[200px] max-h-[580px] flex flex-col bg-background">
      {/* Header */}
      <header className="flex items-center justify-between px-4 py-3 border-b border-foreground/10">
        <div className="flex items-center gap-2">
          <Shield className="w-5 h-5 text-foreground" />
          <span className="text-[15px] font-semibold tracking-tight">
            After<span className="font-normal">Click</span>
          </span>
        </div>
        <span className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground">Companion</span>
      </header>

      <div className="flex-1 overflow-y-auto scroll-area">
        {view === 'home' && (
          <HomeView
            tabInfo={tabInfo}
            restricted={restricted}
            inspectUrl={inspectUrl}
            inspectPageContent={inspectPageContent}
            inspectingPage={inspectingPage}
            pageError={pageError}
            onEmergency={() => setView('emergency')}
          />
        )}
        {view === 'url-results' && urlAnalysis && (
          <UrlResultsView
            tabInfo={tabInfo}
            analysis={urlAnalysis}
            onInspectPage={inspectPageContent}
            inspectingPage={inspectingPage}
            pageError={pageError}
            onCopy={copyFindings}
            copied={copied}
            onReset={resetInspection}
            onEmergency={() => setView('emergency')}
            openWebsite={openWebsite}
          />
        )}
        {view === 'page-results' && pageAnalysis && (
          <PageResultsView
            tabInfo={tabInfo}
            urlAnalysis={urlAnalysis}
            analysis={pageAnalysis}
            onCopy={copyFindings}
            copied={copied}
            onReset={resetInspection}
            onEmergency={() => setView('emergency')}
            openWebsite={openWebsite}
          />
        )}
        {view === 'emergency' && (
          <EmergencyView
            onBack={resetInspection}
            openWebsite={openWebsite}
          />
        )}
      </div>

      {/* Footer */}
      <footer className="px-4 py-2 border-t border-foreground/10 bg-paper/50">
        <p className="text-[10px] text-muted-foreground text-center leading-relaxed">
          AfterClick inspects addresses locally and never visits suspicious links.
          No data is sent externally.
        </p>
      </footer>
    </div>
  );
}

/* ---- Home View ---- */
function HomeView({ tabInfo, restricted, inspectUrl, inspectPageContent, inspectingPage, pageError, onEmergency }: {
  tabInfo: TabInfo | null;
  restricted: boolean;
  inspectUrl: () => void;
  inspectPageContent: () => void;
  inspectingPage: boolean;
  pageError: string | null;
  onEmergency: () => void;
}) {
  let hostname = '';
  let protocol = '';
  try {
    if (tabInfo?.url) {
      const u = new URL(tabInfo.url);
      hostname = u.hostname;
      protocol = u.protocol.replace(':', '');
    }
  } catch { /* ignore */ }

  return (
    <div className="p-4 space-y-4 fade-in">
      <div className="text-center py-2">
        <ShieldQuestion className="w-10 h-10 mx-auto text-foreground/60 mb-2" />
        <p className="text-sm font-medium">Not sure whether to trust this page?</p>
      </div>

      {tabInfo && !restricted && (
        <div className="rounded-lg border border-foreground/10 bg-paper/60 p-3 space-y-1.5">
          <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground">Current page</p>
          <div className="flex items-center gap-2">
            {protocol === 'https' ? (
              <Lock className="w-3.5 h-3.5 text-safe shrink-0" />
            ) : (
              <Unlock className="w-3.5 h-3.5 text-caution shrink-0" />
            )}
            <span className="text-sm font-medium truncate">{hostname}</span>
          </div>
          <p className="text-[11px] text-muted-foreground truncate">{tabInfo.url}</p>
        </div>
      )}

      {restricted && (
        <div className="rounded-lg border border-caution/30 bg-caution/5 p-3">
          <p className="text-xs text-caution font-medium">This is a browser system page</p>
          <p className="text-[11px] text-muted-foreground mt-1">
            Chrome doesn't allow extensions to inspect internal pages. Navigate to a website to use the inspector.
          </p>
        </div>
      )}

      <button
        onClick={inspectUrl}
        disabled={!tabInfo || restricted}
        className="w-full flex items-center justify-center gap-2 rounded-lg bg-primary text-primary-foreground px-4 py-3 text-sm font-medium transition-all hover:opacity-90 disabled:opacity-40 disabled:cursor-not-allowed"
      >
        <Globe className="w-4 h-4" />
        Inspect this page
      </button>

      <button
        onClick={inspectPageContent}
        disabled={!tabInfo || restricted || inspectingPage}
        className="w-full flex items-center justify-center gap-2 rounded-lg border border-foreground/20 bg-paper px-4 py-2.5 text-sm font-medium transition-all hover:border-foreground/40 disabled:opacity-40 disabled:cursor-not-allowed"
      >
        <Eye className="w-4 h-4" />
        {inspectingPage ? 'Inspecting\u2026' : 'Inspect visible page text and links'}
      </button>

      {pageError && (
        <div className="rounded-lg border border-caution/30 bg-caution/5 p-3">
          <p className="text-xs text-caution">{pageError}</p>
        </div>
      )}

      <div className="pt-1">
        <button
          onClick={onEmergency}
          className="w-full flex items-center justify-center gap-2 rounded-lg border border-now/30 bg-now/5 px-4 py-2.5 text-sm font-medium text-now transition-all hover:bg-now/10"
        >
          <ShieldAlert className="w-4 h-4" />
          I already clicked or shared something
        </button>
      </div>
    </div>
  );
}

/* ---- URL Results View ---- */
function UrlResultsView({ tabInfo, analysis, onInspectPage, inspectingPage, pageError, onCopy, copied, onReset, onEmergency, openWebsite }: {
  tabInfo: TabInfo | null;
  analysis: DomainAnalysis;
  onInspectPage: () => void;
  inspectingPage: boolean;
  pageError: string | null;
  onCopy: () => void;
  copied: boolean;
  onReset: () => void;
  onEmergency: () => void;
  openWebsite: (url: string) => void;
}) {
  const hasIssues = analysis.issues.length > 0;
  const highIssues = analysis.issues.filter(i => i.severity === 'high');

  return (
    <div className="p-4 space-y-3 fade-in">
      {/* Status banner */}
      <div className={`rounded-lg p-3 flex items-start gap-3 ${
        highIssues.length > 0 ? 'bg-now/8 border border-now/30' :
        hasIssues ? 'bg-caution/8 border border-caution/30' :
        'bg-foreground/5 border border-foreground/10'
      }`}>
        {highIssues.length > 0 ? <ShieldAlert className="w-5 h-5 text-now shrink-0 mt-0.5" /> :
         hasIssues ? <AlertTriangle className="w-5 h-5 text-caution shrink-0 mt-0.5" /> :
         <ShieldCheck className="w-5 h-5 text-foreground/60 shrink-0 mt-0.5" />}
        <div>
          <p className="text-sm font-medium">
            {highIssues.length > 0 ? 'Warning signs found' :
             hasIssues ? 'Some indicators found' :
             'No known warning signs'}
          </p>
          <p className="text-[11px] text-muted-foreground mt-0.5">
            {highIssues.length > 0 ? 'This URL has characteristics commonly seen in phishing or scam sites.' :
             hasIssues ? 'Review the details below.' :
             "An absence of warnings doesn't guarantee this page is safe."}
          </p>
        </div>
      </div>

      {/* Domain details */}
      <div className="rounded-lg border border-foreground/10 bg-paper/60 p-3 space-y-2">
        <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground">Inspected website</p>
        <div className="space-y-1.5">
          <DetailRow label="Full hostname" value={analysis.hostname ?? 'unknown'} />
          <DetailRow label="Registered domain" value={analysis.registrableDomain ?? 'unknown'} />
          {analysis.subdomain && <DetailRow label="Subdomain" value={analysis.subdomain} />}
          <DetailRow label="HTTPS" value={
            analysis.protocol === 'https' ? 'Yes \u2014 encrypted (does not mean trustworthy)' :
            analysis.protocol === 'http' ? 'No \u2014 unencrypted' : 'N/A'
          } />
          {analysis.isIp && <DetailRow label="IP-based host" value="Yes \u2014 uses a raw IP address instead of a domain name" />}
          {analysis.officialFor && (
            <DetailRow label="Known brand domain" value={`Recognized as an official ${analysis.officialFor.name} domain`} />
          )}
        </div>
      </div>

      {/* Issues */}
      {hasIssues && (
        <div className="space-y-2">
          <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground px-1">Observed indicators</p>
          {analysis.issues.map((issue, i) => (
            <IssueCard key={i} severity={issue.severity} message={issue.message} />
          ))}
        </div>
      )}

      {/* Recommended action */}
      {hasIssues && (
        <div className="rounded-lg border border-foreground/10 bg-paper/60 p-3">
          <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground mb-1.5">Recommended next action</p>
          <p className="text-xs leading-relaxed">
            {highIssues.length > 0
              ? 'Do not enter any personal information on this page. Open the official service independently rather than through this link.'
              : 'Verify the URL independently before entering any information. When in doubt, type the official address yourself.'}
          </p>
        </div>
      )}

      {/* Unknown info */}
      <div className="rounded-lg border border-foreground/10 bg-paper/60 p-3">
        <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground mb-1.5">What the extension cannot establish</p>
        <ul className="text-xs text-muted-foreground space-y-1">
          <li>\u2022 Whether the page is actually malicious (only the URL was analyzed)</li>
          <li>\u2022 Whether any data has already been compromised</li>
          <li>\u2022 The page's actual content or behavior</li>
        </ul>
      </div>

      {/* Action buttons */}
      <div className="space-y-2 pt-1">
        <button
          onClick={onInspectPage}
          disabled={inspectingPage}
          className="w-full flex items-center justify-center gap-2 rounded-lg border border-foreground/20 bg-paper px-4 py-2.5 text-sm font-medium transition-all hover:border-foreground/40 disabled:opacity-40"
        >
          <Eye className="w-4 h-4" />
          {inspectingPage ? 'Inspecting\u2026' : 'Inspect visible page text and links'}
        </button>
        {pageError && (
          <p className="text-xs text-caution px-1">{pageError}</p>
        )}
        <div className="grid grid-cols-2 gap-2">
          <button onClick={onCopy} className="flex items-center justify-center gap-1.5 rounded-lg border border-foreground/15 px-3 py-2 text-xs font-medium transition-all hover:border-foreground/30">
            {copied ? <CheckCircle2 className="w-3.5 h-3.5 text-safe" /> : <Copy className="w-3.5 h-3.5" />}
            {copied ? 'Copied!' : 'Copy findings'}
          </button>
          <button onClick={onReset} className="flex items-center justify-center gap-1.5 rounded-lg border border-foreground/15 px-3 py-2 text-xs font-medium transition-all hover:border-foreground/30">
            <RotateCcw className="w-3.5 h-3.5" />
            Inspect again
          </button>
        </div>
        <button
          onClick={onEmergency}
          className="w-full flex items-center justify-center gap-2 rounded-lg border border-now/30 bg-now/5 px-4 py-2.5 text-sm font-medium text-now transition-all hover:bg-now/10"
        >
          <ShieldAlert className="w-4 h-4" />
          I already interacted
        </button>
      </div>
    </div>
  );
}

/* ---- Page Results View ---- */
function PageResultsView({ tabInfo, urlAnalysis, analysis, onCopy, copied, onReset, onEmergency, openWebsite }: {
  tabInfo: TabInfo | null;
  urlAnalysis: DomainAnalysis | null;
  analysis: PageContentAnalysis;
  onCopy: () => void;
  copied: boolean;
  onReset: () => void;
  onEmergency: () => void;
  openWebsite: (url: string) => void;
}) {
  const { textAnalysis, linkMismatches, truncated } = analysis;
  const allFindings = textAnalysis.findings;
  const highFindings = allFindings.filter(f => f.severity === 'high');

  return (
    <div className="p-4 space-y-3 fade-in">
      {/* Status banner */}
      <div className={`rounded-lg p-3 flex items-start gap-3 ${
        highFindings.length > 0 ? 'bg-now/8 border border-now/30' :
        allFindings.length > 0 ? 'bg-caution/8 border border-caution/30' :
        'bg-foreground/5 border border-foreground/10'
      }`}>
        {highFindings.length > 0 ? <ShieldAlert className="w-5 h-5 text-now shrink-0 mt-0.5" /> :
         allFindings.length > 0 ? <AlertTriangle className="w-5 h-5 text-caution shrink-0 mt-0.5" /> :
         <ShieldCheck className="w-5 h-5 text-foreground/60 shrink-0 mt-0.5" />}
        <div>
          <p className="text-sm font-medium">{textAnalysis.headline}</p>
          <p className="text-[11px] text-muted-foreground mt-0.5">
            Based on visible text and link analysis.
            {truncated && ' (Page text was truncated for safety.)'}
          </p>
        </div>
      </div>

      {/* URL info (if already inspected) */}
      {urlAnalysis && (
        <div className="rounded-lg border border-foreground/10 bg-paper/60 p-3 space-y-1.5">
          <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground">Inspected website</p>
          <DetailRow label="Hostname" value={urlAnalysis.hostname ?? 'unknown'} />
          <DetailRow label="Registered domain" value={urlAnalysis.registrableDomain ?? 'unknown'} />
        </div>
      )}

      {/* Text findings */}
      {allFindings.length > 0 && (
        <div className="space-y-2">
          <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground px-1">
            Warning signs in page text
          </p>
          {allFindings.map((f, i) => (
            <FindingCard key={i} finding={f} />
          ))}
        </div>
      )}

      {/* Link mismatches */}
      {linkMismatches.length > 0 && (
        <div className="space-y-2">
          <p className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground px-1">
            Link mismatches
          </p>
          {linkMismatches.map((m, i) => (
            <div key={i} className="rounded-lg border border-now/30 bg-now/5 p-3">
              <p className="text-xs font-medium text-now">Displayed text and actual link don't match</p>
              <p className="text-[11px] text-muted-foreground mt-1">
                Shows: <span className="font-mono">{m.displayedDomain}</span>
                {' \u2192 Actually goes to: '}
                <span className="font-mono font-medium">{m.actualDomain}</span>
              </p>
            </div>
          ))}
        </div>
      )}

      {/* No findings */}
      {allFindings.length === 0 && linkMismatches.length === 0 && (
        <div className="rounded-lg border border-foreground/10 bg-paper/60 p-3">
          <p className="text-xs text-muted-foreground leading-relaxed">
            No known warning signs were found in the visible page text. This does not confirm the page is safe \u2014
            only that commonly recognized scam patterns weren't detected.
          </p>
        </div>
      )}

      {/* Action buttons */}
      <div className="space-y-2 pt-1">
        <div className="grid grid-cols-2 gap-2">
          <button onClick={onCopy} className="flex items-center justify-center gap-1.5 rounded-lg border border-foreground/15 px-3 py-2 text-xs font-medium transition-all hover:border-foreground/30">
            {copied ? <CheckCircle2 className="w-3.5 h-3.5 text-safe" /> : <Copy className="w-3.5 h-3.5" />}
            {copied ? 'Copied!' : 'Copy findings'}
          </button>
          <button onClick={onReset} className="flex items-center justify-center gap-1.5 rounded-lg border border-foreground/15 px-3 py-2 text-xs font-medium transition-all hover:border-foreground/30">
            <RotateCcw className="w-3.5 h-3.5" />
            Inspect again
          </button>
        </div>
        <button onClick={() => openWebsite(WEBSITE_URL)} className="w-full flex items-center justify-center gap-2 rounded-lg border border-foreground/20 bg-paper px-4 py-2.5 text-sm font-medium transition-all hover:border-foreground/40">
          <ExternalLink className="w-4 h-4" />
          Open full AfterClick guide
        </button>
        <button
          onClick={onEmergency}
          className="w-full flex items-center justify-center gap-2 rounded-lg border border-now/30 bg-now/5 px-4 py-2.5 text-sm font-medium text-now transition-all hover:bg-now/10"
        >
          <ShieldAlert className="w-4 h-4" />
          I already interacted
        </button>
      </div>
    </div>
  );
}

/* ---- Emergency View ---- */
function EmergencyView({ onBack, openWebsite }: {
  onBack: () => void;
  openWebsite: (url: string) => void;
}) {
  const incidents = [
    { type: 'password', label: 'I entered a password', icon: KeyRound, color: 'text-foreground' },
    { type: 'code', label: 'I shared a verification code', icon: MessageSquareWarning, color: 'text-foreground' },
    { type: 'payment', label: 'I sent money', icon: DollarSign, color: 'text-now' },
    { type: 'download', label: 'I downloaded or opened something suspicious', icon: Download, color: 'text-foreground' },
    { type: 'remote', label: 'I let someone remotely control my computer', icon: MonitorSmartphone, color: 'text-foreground' },
    { type: 'link', label: 'I only clicked a link', icon: MousePointerClick, color: 'text-foreground' },
  ];

  return (
    <div className="p-4 space-y-3 fade-in">
      <div className="flex items-center gap-3 mb-1">
        <button onClick={onBack} className="text-xs text-muted-foreground hover:text-foreground transition-colors">
          \u2190 Back
        </button>
      </div>

      <div className="text-center py-1">
        <ShieldAlert className="w-8 h-8 mx-auto text-now mb-2" />
        <p className="text-sm font-medium">What happened?</p>
        <p className="text-[11px] text-muted-foreground mt-1">
          Pick the closest match. AfterClick will guide you through what to do.
        </p>
      </div>

      <div className="space-y-2">
        {incidents.map(({ type, label, icon: Icon, color }) => (
          <button
            key={type}
            onClick={() => openWebsite(getIncidentUrl(type))}
            className={`w-full flex items-center gap-3 rounded-lg border bg-paper/60 px-3.5 py-3 text-left text-sm transition-all hover:-translate-y-0.5 hover:border-foreground/40 ${
              type === 'payment' ? 'border-now/40' : 'border-foreground/15'
            }`}
          >
            <Icon className={`w-4 h-4 shrink-0 ${color}`} />
            <span className="flex-1">{label}</span>
            <ExternalLink className="w-3.5 h-3.5 text-muted-foreground" />
          </button>
        ))}
      </div>

      <p className="text-[10px] text-muted-foreground text-center pt-1 leading-relaxed">
        This opens the AfterClick website with the right emergency workflow.
        No personal data is transferred \u2014 only the incident type.
      </p>
    </div>
  );
}

/* ---- Shared Components ---- */
function DetailRow({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex items-start gap-2">
      <span className="text-[10px] font-mono uppercase tracking-wider text-muted-foreground w-[100px] shrink-0 pt-0.5">{label}</span>
      <span className="text-xs break-all flex-1">{value}</span>
    </div>
  );
}

function IssueCard({ severity, message }: { severity: string; message: string }) {
  return (
    <div className={`rounded-lg p-3 border ${
      severity === 'high' ? 'bg-now/5 border-now/25' :
      severity === 'medium' ? 'bg-caution/5 border-caution/25' :
      'bg-foreground/3 border-foreground/10'
    }`}>
      <div className="flex items-center gap-1.5 mb-1">
        <span className={`text-[10px] font-mono uppercase tracking-wider ${
          severity === 'high' ? 'text-now' : severity === 'medium' ? 'text-caution' : 'text-muted-foreground'
        }`}>{severity}</span>
      </div>
      <p className="text-xs leading-relaxed">{message}</p>
    </div>
  );
}

function FindingCard({ finding }: { finding: import('@/lib/inspector').Finding }) {
  const [expanded, setExpanded] = useState(false);
  return (
    <div className={`rounded-lg p-3 border ${
      finding.severity === 'high' ? 'bg-now/5 border-now/25' :
      finding.severity === 'medium' ? 'bg-caution/5 border-caution/25' :
      'bg-foreground/3 border-foreground/10'
    }`}>
      <button onClick={() => setExpanded(!expanded)} className="w-full flex items-start justify-between gap-2 text-left">
        <div>
          <div className="flex items-center gap-1.5 mb-0.5">
            <span className={`text-[10px] font-mono uppercase tracking-wider ${
              finding.severity === 'high' ? 'text-now' : finding.severity === 'medium' ? 'text-caution' : 'text-muted-foreground'
            }`}>{finding.severity}</span>
          </div>
          <p className="text-xs font-medium">{finding.title}</p>
        </div>
        {expanded ? <ChevronUp className="w-3.5 h-3.5 text-muted-foreground shrink-0 mt-1" /> : <ChevronDown className="w-3.5 h-3.5 text-muted-foreground shrink-0 mt-1" />}
      </button>
      {expanded && (
        <div className="mt-2 space-y-1.5">
          <p className="text-[11px] text-muted-foreground leading-relaxed">{finding.explanation}</p>
          {finding.evidence.length > 0 && (
            <div className="text-[11px]">
              <span className="text-muted-foreground">Evidence: </span>
              {finding.evidence.slice(0, 3).map((e, i) => (
                <span key={i} className="inline-block bg-caution/15 rounded px-1 py-0.5 font-mono text-[10px] mr-1 mb-0.5">
                  "{e.text}"
                </span>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
}
